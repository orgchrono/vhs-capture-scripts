def main():
    print("[*] Synchronizing new features and preferences across all 10 locales...")
    for loc in SUPPORTED_LOCALES:
        locale_data = load_locale(loc)
        for namespace, translations_map in NEW_TRANSLATIONS.items():
            if namespace not in locale_data:
                locale_data[namespace] = {}
            if loc in translations_map:
                locale_data[namespace].update(translations_map[loc])
        save_locale(loc, locale_data)
        print(f"  [+] {loc} synchronized successfully.")

    print("[*] Synchronization complete.")


if __name__ == "__main__":
    main()
