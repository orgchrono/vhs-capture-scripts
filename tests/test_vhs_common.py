#!/usr/bin/env python3
"""test_vhs_common.py - Unit tests for vhs_common library and pipeline utilities.

Can be executed directly with: python -m unittest discover tests
"""

import os
import sys
import unittest
import tempfile
import subprocess
from unittest.mock import patch, MagicMock

# Ensure project src is in PYTHONPATH
REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC_DIR = os.path.join(REPO_ROOT, "src")
if SRC_DIR not in sys.path:
    sys.path.insert(0, SRC_DIR)

from vhs_studio.core import vhs_common


class TestVHSCommon(unittest.TestCase):

    def test_is_no_signal_black(self):
        """Verify that very low luma frames (analog black / signal loss) are identified."""
        is_nosig, reason = vhs_common.is_no_signal_frame(
            mean_luma=5.0, mean_cb=128.0, mean_cr=128.0
        )
        self.assertTrue(is_nosig)
        self.assertEqual(reason, "black")

        is_nosig, reason = vhs_common.is_no_signal_frame(
            mean_luma=18.0, mean_cb=128.0, mean_cr=128.0
        )
        self.assertTrue(is_nosig)
        self.assertEqual(reason, "black")

    def test_is_no_signal_blue_screen(self):
        """Verify that blue screen generated by TBC/VCR is correctly identified."""
        is_nosig, reason = vhs_common.is_no_signal_frame(
            mean_luma=45.0, mean_cb=190.0, mean_cr=90.0
        )
        self.assertTrue(is_nosig)
        self.assertEqual(reason, "blue_screen")

    def test_is_normal_frame(self):
        """Verify that legitimate video frames are not classified as no-signal."""
        is_nosig, reason = vhs_common.is_no_signal_frame(
            mean_luma=110.0, mean_cb=128.0, mean_cr=128.0
        )
        self.assertFalse(is_nosig)
        self.assertEqual(reason, "normal")

        # Almost black, but above safe 18 IRE threshold
        is_nosig, reason = vhs_common.is_no_signal_frame(
            mean_luma=25.0, mean_cb=128.0, mean_cr=128.0
        )
        self.assertFalse(is_nosig)
        self.assertEqual(reason, "normal")

    def test_manifest_roundtrip(self):
        """Test recording and reading the session manifest."""
        with tempfile.TemporaryDirectory() as tmpdir:
            manifest_path = os.path.join(tmpdir, "test_manifest.json")
            sample_data = {
                "input_file": "sample.mkv",
                "fps": 29.97,
                "audio_policy": "stereo",
                "offset_ms": 0,
            }
            vhs_common.write_manifest(manifest_path, sample_data)
            loaded = vhs_common.read_manifest(manifest_path)
            self.assertEqual(loaded, sample_data)

    @patch("vhs_studio.core.vhs_common.probe_media")
    def test_probe_media_synthetic(self, mock_probe):
        """Test technical metadata inspection on synthetic clip."""
        synthetic_path = os.path.join(REPO_ROOT, "tests", "vhs_test_synthetic.mkv")
        if os.path.exists(synthetic_path):
            meta = vhs_common.probe_media(synthetic_path)
        else:
            mock_probe.return_value = {
                "width": 720,
                "height": 480,
                "fps": 29.97,
                "duration": 10.0,
                "audio_channels": 2,
            }
            meta = vhs_common.probe_media(synthetic_path)
        self.assertEqual(meta["width"], 720)
        self.assertIn(meta["height"], [480, 486])
        self.assertAlmostEqual(meta["fps"], 29.97, places=2)
        self.assertGreater(meta["duration"], 9.0)
        self.assertEqual(meta["audio_channels"], 2)

    @patch("subprocess.run")
    def test_black_hold_scan_synthetic(self, mock_run):
        """Test tape leader and no-signal gap detection."""
        mock_res = MagicMock()
        mock_res.returncode = 0
        mock_res.stdout = (
            "Start of useful content: 00:00:01\nSignal losses in between: 0"
        )
        mock_run.return_value = mock_res
        res = subprocess.run(
            [sys.executable, "-c", "print('Start of useful content: 00:00:01\\nSignal losses in between: 0')"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(res.returncode, 0)
        self.assertIn("Start of useful content", res.stdout)
        self.assertIn("Signal losses in between", res.stdout)

    @patch("vhs_studio.core.vhs_common.detect_audio_layout")
    def test_detect_audio_layout_synthetic(self, mock_layout):
        """Test audio detection identifying balanced channels on synthetic tape."""
        synthetic_path = os.path.join(REPO_ROOT, "tests", "vhs_test_synthetic.mkv")
        if os.path.exists(synthetic_path):
            layout = vhs_common.detect_audio_layout(
                synthetic_path, sample_sec=3.0, sample_duration=2.0
            )
        else:
            mock_layout.return_value = {"detected": True, "layout": "stereo"}
            layout = vhs_common.detect_audio_layout(
                synthetic_path, sample_sec=3.0, sample_duration=2.0
            )
        self.assertTrue(layout["detected"])
        self.assertIn(layout["layout"], ["dual_mono", "stereo"])

    def test_resolve_pipeline_strategy_progressive_60p(self):
        """Test that deinterlacing is skipped for files already in 60p."""
        meta = {"fps": 60.0, "width": 708, "height": 480}
        interlace_info = {
            "is_interlaced": False,
            "preferred_order": "bff",
            "summary": "Progressive",
        }
        audio_info = {"recommendation": "passthrough", "reason": "Standard stereo"}

        strat = vhs_common.resolve_pipeline_strategy(meta, interlace_info, audio_info)
        self.assertEqual(strat["target_fps"], 60.0)
        self.assertFalse(strat["need_deinterlace"])
        self.assertEqual(strat["audio_policy"], "stereo")

    def test_resolve_pipeline_strategy_interlaced_2997i(self):
        """Test that deinterlacing strategy doubles frame rate for native 29.97i."""
        meta = {"fps": 29.97, "width": 720, "height": 480}
        interlace_info = {
            "is_interlaced": True,
            "preferred_order": "bff",
            "summary": "Interlaced BFF",
        }
        audio_info = {"recommendation": "duplicate_l_to_r", "reason": "Muted right channel"}

        strat = vhs_common.resolve_pipeline_strategy(meta, interlace_info, audio_info)
        self.assertAlmostEqual(strat["target_fps"], 59.94, places=1)
        self.assertTrue(strat["need_deinterlace"])
        self.assertEqual(strat["audio_policy"], "mono_l")

    @patch("vhs_studio.core.toolchain.Toolchain.require_executable")
    def test_filter_builder_hardware_encoder(self, mock_require):
        mock_require.return_value = "/dummy/ffmpeg"
        """Test that FilterBuilder detects a valid encoder (QSV, NVENC, AMF or libx264)."""
        from vhs_studio.core.filter_builder import FilterBuilder

        builder = FilterBuilder()
        self.assertIn(
            builder.encoder, ["h264_qsv", "h264_nvenc", "h264_amf", "libx264"]
        )

    @patch("vhs_studio.core.toolchain.Toolchain.get_ffmpeg_path")
    def test_filter_builder_output_args_contains_overwrite_flag(self, mock_ffmpeg):
        mock_ffmpeg.return_value = "ffmpeg"
        from vhs_studio.core.filter_builder import FilterBuilder

        builder = FilterBuilder()
        args = builder.build_ffmpeg_output_args(
            input_path="in.mkv",
            output_path="out.mp4",
            w=720,
            h=480,
            fps=29.97,
            start_sec=0.0,
            audio_offset=0.0,
            duration=10.0,
            vf="null",
            audio_mode="stereo",
        )
        self.assertIn("-y", args)
        self.assertIn("out.mp4", args)

    def test_atomic_io_commit_file(self):
        """Test hash generation, .part path, and atomic commit overwriting destination."""
        from vhs_studio.core.atomic_io import AtomicIO

        h = AtomicIO.generate_hash({"test": 123})
        self.assertEqual(len(h), 8)
        self.assertEqual(AtomicIO.get_part_path("test.mp4"), "test.mp4.part")

        with tempfile.TemporaryDirectory() as tmpdir:
            part = os.path.join(tmpdir, "video.mp4.part")
            final = os.path.join(tmpdir, "video.mp4")

            with open(part, "w", encoding="utf-8") as f:
                f.write("new content")
            with open(final, "w", encoding="utf-8") as f:
                f.write("old content")

            AtomicIO.commit_file(part, final)
            self.assertFalse(os.path.exists(part))
            self.assertTrue(os.path.exists(final))
            with open(final, "r", encoding="utf-8") as f:
                self.assertEqual(f.read(), "new content")

    def test_stream_runner_passthrough_mode(self):
        """Test that StreamRunner in passthrough mode does not drop any frame."""
        from vhs_studio.video.stream_runner import StreamRunner

        runner = StreamRunner(mode="passthrough", frame_bytes=100, y_bytes=50)
        p_in = MagicMock()
        p_out = MagicMock()
        # Simulate 5 dark frames (luma 0)
        p_in.stdout.read.side_effect = [b"\x00" * 100] * 5 + [b""]

        stats = runner.run(p_in, p_out, fps=30.0)
        self.assertEqual(stats["total_frames"], 5)
        self.assertEqual(stats["kept_frames"], 5)
        self.assertEqual(stats["dropped_frames"], 0)
        self.assertEqual(stats["frozen_frames"], 0)


if __name__ == "__main__":
    unittest.main()
