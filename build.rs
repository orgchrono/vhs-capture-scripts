use std::fs;
use std::path::Path;

fn main() {
    #[cfg(windows)]
    {
        let attrs = tauri_build::Attributes::new()
            .windows_attributes(tauri_build::WindowsAttributes::new_without_app_manifest());
        tauri_build::try_build(attrs).expect("failed to run tauri-build");
    }
    #[cfg(not(windows))]
    {
        tauri_build::build();
    }

    generate_embedded_assets();

    println!("cargo:rerun-if-changed=ui/dist");
    println!("cargo:rerun-if-changed=tools/panasonic_rec");
}

fn generate_embedded_assets() {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let dest_path = Path::new(&out_dir).join("embedded_assets_gen.rs");

    let mut code = String::new();
    code.push_str("// Auto-generated by build.rs. Do not edit.\n\n");

    // 1. Embedded UI
    let ui_dist = Path::new("ui/dist");
    let mut ui_entries = Vec::new();

    if ui_dist.exists() && ui_dist.is_dir() {
        let mut dirs = vec![ui_dist.to_path_buf()];
        while let Some(current) = dirs.pop() {
            if let Ok(entries) = fs::read_dir(&current) {
                for entry in entries.flatten() {
                    let path = entry.path();
                    if path.is_dir() {
                        dirs.push(path);
                    } else if path.is_file() {
                        if let Ok(rel) = path.strip_prefix(ui_dist) {
                            let rel_str = rel.to_string_lossy().replace('\\', "/");
                            let abs_path = fs::canonicalize(&path).unwrap_or(path.clone());
                            let abs_str = abs_path.to_string_lossy().replace('\\', "/");
                            let mime = guess_mime_type(&rel_str);
                            ui_entries.push((rel_str, abs_str, mime));
                        }
                    }
                }
            }
        }
    }

    code.push_str("pub fn get_embedded_ui_asset(rel_path: &str) -> Option<(&'static [u8], &'static str)> {\n");
    code.push_str("    match rel_path.trim_start_matches('/') {\n");
    for (rel, abs, mime) in &ui_entries {
        code.push_str(&format!(
            "        {:?} => Some((include_bytes!({:?}), {:?})),\n",
            rel, abs, mime
        ));
    }
    code.push_str("        _ => None,\n");
    code.push_str("    }\n");
    code.push_str("}\n\n");

    // 2. Embedded Panasonic Tools
    code.push_str("pub fn extract_embedded_tools(target_dir: &std::path::Path) -> std::io::Result<()> {\n");
    code.push_str("    std::fs::create_dir_all(target_dir)?;\n");

    let tools_dir = Path::new("tools/panasonic_rec");
    let tool_names = ["extract_meihdfs.exe", "dvd-vr.exe", "udf_dump.exe"];
    let mut has_tools = false;

    for name in tool_names {
        let p = tools_dir.join(name);
        if p.is_file() {
            if let Ok(abs) = fs::canonicalize(&p) {
                let abs_str = abs.to_string_lossy().replace('\\', "/");
                code.push_str(&format!(
                    "    let p = target_dir.join({:?});\n    if !p.exists() {{\n        let _ = std::fs::write(&p, include_bytes!({:?}));\n    }}\n",
                    name, abs_str
                ));
                has_tools = true;
            }
        }
    }

    if !has_tools {
        code.push_str("    let _ = target_dir;\n");
    }
    code.push_str("    Ok(())\n");
    code.push_str("}\n");

    fs::write(&dest_path, code).expect("failed to write embedded_assets_gen.rs");
}

fn guess_mime_type(path: &str) -> &'static str {
    if path.ends_with(".html") || path.ends_with(".htm") {
        "text/html; charset=utf-8"
    } else if path.ends_with(".js") || path.ends_with(".mjs") {
        "application/javascript; charset=utf-8"
    } else if path.ends_with(".css") {
        "text/css; charset=utf-8"
    } else if path.ends_with(".json") {
        "application/json; charset=utf-8"
    } else if path.ends_with(".svg") {
        "image/svg+xml"
    } else if path.ends_with(".png") {
        "image/png"
    } else if path.ends_with(".ico") {
        "image/x-icon"
    } else if path.ends_with(".woff2") {
        "font/woff2"
    } else {
        "application/octet-stream"
    }
}
